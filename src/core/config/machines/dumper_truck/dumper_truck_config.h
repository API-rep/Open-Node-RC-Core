/*!****************************************************************************
 * @file  dumper_truck_config.h
 * @brief Dumper-truck machine-class sub-umbrella.
 *
 * @details Conditionally includes all config sub-modules for the dumper-truck /
 *          articulated hauler vehicle class.  Consumers include this file via
 *          machine_type.h — they never reference the vehicle-class path
 *          directly.
 *
 *          Sub-modules included:
 *            combus   — always (generated BASE channel IDs, <combus_base_ids.h>)
 *            motion   — always (traction preset alias)
 *            inputs_map — not included here (see note below)
 *            sound    — if SOUND_ENABLED is defined (no env defines it yet;
 *                       see the Machine / Sound convergence in doc/roadmap.md)
 *
 *          NOTE: `sound_dynamics.h` (standalone dispatcher) is no longer
 *          needed — sound profile inclusion is handled here.
 *******************************************************************************
 */
#pragma once

#include <machines/config/machines/machines.h> // MACHINE_TYPE_*


#if defined(MACHINE_TYPE_DUMPER_TRUCK)

  // =============================================================================
  // 1. COMBUS  (always)
  // =============================================================================

  // Generic BASE vocabulary for dumper-truck code (AnalogComBusBaseID /
  // DigitalComBusBaseID). The header is GENERATED by the ComBus Builder under
  // <build_dir>/combus_generated/, which the SCons hook adds to the include
  // path. Machine-specific code includes the generated <combus.h> directly.
  #include <combus_base_ids.h>

  
  // =============================================================================
  // 2. MOTION PRESET ALIAS  (always)
  // =============================================================================
  
  #include <core/config/machines/dumper_truck/motion/dumper_truck_motion.h>
  
  
  // =============================================================================
  // 3. INPUT MAPPING
  // =============================================================================
  // NOTE: the input mapping lives in dumper_truck/inputs/inputs_map/ and is
  // not included here: input_update.cpp includes inputs_map.h directly.
  
  
  // =============================================================================
  // 4. SOUND DYNAMICS  (only when SOUND_ENABLED is defined — no env defines it yet)
  // =============================================================================
  
  #if defined(SOUND_ENABLED)
    #include <core/config/machines/dumper_truck/sound/dumper_truck_sound.h>
  #endif
  
#endif  // MACHINE_TYPE_DUMPER_TRUCK

// EOF dumper_truck_config.h