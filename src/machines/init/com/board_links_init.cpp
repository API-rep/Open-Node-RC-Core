/******************************************************************************
 * @file  board_links_init.cpp
 * @brief ComBus links of the board: from its table to running links.
 *
 * @details The table of the board (comLinks[], envCfg.h) gives each link: a
 *   ComDev of the node, the port of the board and the role of this end.  This
 *   file owns the storage of the links and hands the table to
 *   combus_links_init(), which checks each link, opens its port and starts it.
 *****************************************************************************/

#include "board_links_init.h"

#include <machines/config/config.h>                          // comLinks[], comLinksCount
#include <core/config/com/combus_uart.h>                     // ComBusUartMaxTxHz
#include <core/system/combus/protocol/link/combus_links.h>   // combus_links_init()
#include <combus.h>                                          // generated by the ComBus Builder: comBus
#include "../sys/sys_init.h"                                 // pinReg



// =============================================================================
// 1. STORAGE
// =============================================================================

	// One slot per link of the board.
static CombusTxState  s_txStates[comLinksCount];
static CombusRxState  s_rxStates[comLinksCount];
static ComLinkRuntime s_runtime[comLinksCount];
static ComBusLink     s_links[comLinksCount];



// =============================================================================
// 2. BOARD LINKS INIT
// =============================================================================

/**
 * @brief Links bring-up. One link per entry of the board table.
 *
 * @details In order:
 *   1. The protocol of the extension link fits the controller: checked at compile
 *      time (the line rate against the port is checked by combus_link_check()).
 *   2. combus_links_init() on the table, with the storage of this file.
 */

void board_links_init()
{
		// 1. Protocol
	static_assert(kComProtoExt.txHz > 0u && kComProtoExt.txHz <= ComBusUartMaxTxHz,
	              "Extension link txHz out of range [1, ComBusUartMaxTxHz]");

		// 2. Links
	const ComLinksStorage storage = { s_txStates, s_rxStates, s_runtime, s_links };

	combus_links_init(comLinks, comLinksCount, storage, &pinReg, &comBus);
}

