/******************************************************************************
 * @file  combus_uart_init.cpp
 * @brief ComBus link of the board: from the build flag to a running link.
 *
 * @details Chooses the ComDev and the board port from the COMBUS_UART* flag, then
 *   hands the wiring to combus_links_init(), which opens the port and starts the
 *   link.  The flags are transitional: they select the wiring until the board
 *   declares its own ComDevMap table.
 *****************************************************************************/

#if defined(COMBUS_UART_TX) || defined(COMBUS_UART)

#include "combus_uart_init.h"

#include <machines/config/config.h>                          // comPorts[], UartMaxBaud, kComDevExtUni, kComDevExtBi
#include <core/config/com/combus_uart.h>                     // ComBusUartMaxTxHz
#include <core/system/combus/protocol/link/combus_links.h>   // combus_links_init()
#include <core/system/debug/logging/debug.h>
#include <combus.h>                                          // generated by the ComBus Builder: comBus
#include "../sys/sys_init.h"                                 // pinReg



// =============================================================================
// 1. BOARD PORT LOOKUP
// =============================================================================

	/// The board port that is UART number `uartIdx`, or nullptr if the board has none.
static const ComPort* findUartPort( uint8_t uartIdx )
{
		// Each port of the board
	for (uint8_t i = 0u; i < comPortsCount; ++i) {
		if (comPorts[i].type == ComPortType::UART && comPorts[i].uart.index == uartIdx) {
			return &comPorts[i];
		}
	}

	return nullptr;
}



// =============================================================================
// 2. COMBUS UART INIT
// =============================================================================

/**
 * @brief ComBus link bring-up. One link, chosen by the build flag.
 *
 * @details In order:
 *   1. The protocol fits the board: checked at compile time.
 *   2. The flag gives the ComDev, the UART number and the role of this end:
 *      COMBUS_UART=N, both ways; COMBUS_UART_TX=N, transmit only.
 *   3. The board port of that UART; none: the link is not started, and it is logged.
 *   4. The wiring and its storage, static and owned here, then combus_links_init().
 */

void combus_uart_init()
{
		// 1. Protocol
	static_assert(kComProtoExt.rate <= UartMaxBaud,
	              "Extension link rate exceeds board hardware ceiling UartMaxBaud");
	static_assert(kComProtoExt.txHz > 0u && kComProtoExt.txHz <= ComBusUartMaxTxHz,
	              "Extension link txHz out of range [1, ComBusUartMaxTxHz]");

		// 2. ComDev, UART and role
#if defined(COMBUS_UART)
	constexpr uint8_t uartCh = COMBUS_UART;
	const ComDev*     dev    = &kComDevExtBi;
	constexpr LinkEnd end    = LinkEnd::TX_RX;
#else
	constexpr uint8_t uartCh = COMBUS_UART_TX;
	const ComDev*     dev    = &kComDevExtUni;
	constexpr LinkEnd end    = LinkEnd::TX;
#endif

		// 3. Board port
	const ComPort* port = findUartPort(uartCh);

	if (port == nullptr) {
		sys_log_err("[COMBUS_UART] this board has no UART%u port — ComBus link not started\n", (unsigned)uartCh);
		return;
	}

		// 4. Wiring and storage: its size is the link count
	const ComDevMap maps[] = { { dev, port, end } };
	constexpr uint8_t kLinkCount = 1u;

	static CombusTxState  txStates[kLinkCount];
	static CombusRxState  rxStates[kLinkCount];
	static ComLinkRuntime runtime[kLinkCount];
	static ComBusLink     links[kLinkCount];
	const ComLinksStorage storage = { txStates, rxStates, runtime, links };

	combus_links_init(maps, kLinkCount, storage, &pinReg, &comBus);
}

#endif  // COMBUS_UART_TX / COMBUS_UART

